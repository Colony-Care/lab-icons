import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'src/react/generated')
const icons = JSON.parse(readFileSync(join(root, 'metadata/icons.json'), 'utf8'))
const species = icons.filter((i) => i.set === 'species')

const pascal = (slug) =>
  slug.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('')

rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

const exports = []
for (const icon of species) {
  const svg = readFileSync(join(root, icon.file), 'utf8').trim()
  const match = svg.match(/^<svg\b[^>]*\sviewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>$/)
  if (!match) throw new Error(`Unexpected SVG shape: ${icon.file}`)
  const [, viewBox, body] = match
  const name = `${pascal(icon.slug)}Icon`
  writeFileSync(
    join(outDir, `${name}.ts`),
    `// Generated by scripts/generate-react.mjs. Do not edit.\n` +
      `import { createIcon } from '../createIcon'\n\n` +
      `export const ${name} = createIcon(${JSON.stringify(name)}, ${JSON.stringify(viewBox)}, ${JSON.stringify(body)})\n`,
  )
  exports.push(`export { ${name} } from './generated/${name}'`)
}

writeFileSync(
  join(root, 'src/react/index.ts'),
  `// Generated by scripts/generate-react.mjs. Do not edit.\n${exports.join('\n')}\nexport type { IconProps } from './createIcon'\n`,
)
console.log(`Generated ${species.length} components`)
