import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'src/react/generated')
const icons = JSON.parse(readFileSync(join(root, 'metadata/icons.json'), 'utf8'))
const components = icons.filter((i) => i.set === 'species' || i.set === 'lab')
const STYLES = ['outline', 'solid', 'duotone', 'inverse']

const pascal = (slug) =>
  slug.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('')

const reactAttr = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase())

function parse(file) {
  const svg = readFileSync(join(root, file), 'utf8').trim()
  const match = svg.match(/^<svg\b([^>]*)>([\s\S]*)<\/svg>$/)
  if (!match) throw new Error(`Unexpected SVG shape: ${file}`)
  const [, rootAttrs, body] = match
  const viewBox = rootAttrs.match(/\sviewBox="([^"]+)"/)?.[1]
  if (!viewBox) throw new Error(`Missing viewBox: ${file}`)
  const attrs = {}
  for (const [, k, v] of rootAttrs.matchAll(/\s([\w:-]+)="([^"]*)"/g)) {
    if (k === 'viewBox' || k === 'xmlns') continue
    attrs[reactAttr(k)] = v
  }
  return { viewBox, variant: { attrs, body } }
}

rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

const exports = []
for (const icon of components) {
  const lab = icon.set === 'lab'
  const styles = lab ? STYLES : ['outline']
  const variants = {}
  let viewBox
  for (const s of styles) {
    const file = lab ? icon.styles[s] : icon.file
    const parsed = parse(file)
    if (viewBox && viewBox !== parsed.viewBox) throw new Error(`viewBox differs across styles: ${icon.slug}`)
    viewBox = parsed.viewBox
    variants[s] = parsed.variant
  }
  const name = `${pascal(icon.slug)}Icon`
  const props = lab ? 'LabIconProps' : 'IconProps'
  writeFileSync(
    join(outDir, `${name}.ts`),
    `// Generated by scripts/generate-react.mjs. Do not edit.\n` +
      `import { createIcon } from '../createIcon'\n` +
      `import type { ${props} } from '../createIcon'\n\n` +
      `export const ${name} = /* @__PURE__ */ createIcon<${props}>(${JSON.stringify(name)}, ${JSON.stringify(viewBox)}, ${JSON.stringify(variants)})\n`,
  )
  exports.push(`export { ${name} } from './generated/${name}'`)
}

writeFileSync(
  join(root, 'src/react/index.ts'),
  `// Generated by scripts/generate-react.mjs. Do not edit.\n${exports.join('\n')}\nexport type { IconProps, LabIconProps, IconStyle } from './createIcon'\n`,
)
console.log(`Generated ${components.length} components`)
